import json
from pathlib import Path

OUTPUT_DIR = Path("outputs")

# Friendly labels for the loan terms table, in display order
TERM_LABELS = {
    "reference": "Reference",
    "borrower_name": "Borrower",
    "sector": "Sector",
    "years_trading": "Years trading",
    "loan_amount": "Loan amount",
    "tenor_years": "Tenor (years)",
    "ltv_percent": "Loan-to-value (%)",
    "dscr": "DSCR (x)",
    "net_debt_to_ebitda": "Net debt / EBITDA (x)",
    "personal_guarantee": "Personal guarantee",
    "guarantee_details": "Guarantee details",
    "collateral_description": "Security",
    "collateral_valuation": "Collateral valuation",
    "financial_covenants": "Financial covenants",
    "kyc_complete": "KYC complete",
    "audited_accounts_provided": "Audited accounts provided",
    
}

STATUS_ICONS = {"PASS": "✅ Pass", "FAIL": "❌ Fail", "UNABLE_TO_VERIFY": "⚠️ Unable to verify"}


def format_value(key, value):
    """Turns raw values into readable text for the report."""
    if value is None:
        return "Not stated"
    if isinstance(value, bool):
        return "Yes" if value else "No"
    if key in ("loan_amount", "collateral_valuation"):
        return f"£{value:,.0f}"
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def build_markdown(state: dict, source_file: str) -> str:
    terms = state.get("terms")
    compliance = state.get("compliance_results")
    risk = state.get("risk")
    decision = state["human_decision"]
    completeness = state.get("completeness") or {}

    lines = [
        "# SME Loan Deal Review",
        "",
        f"**Source document:** `{source_file}`  ",
        f"**Decision date:** {decision['decided_at']}",
        "",
        "## Decision",
        "",
        "| | |",
        "|---|---|",
        f"| **Final decision** | **{decision['final_decision']}** |",
        f"| AI recommendation | {decision['ai_recommendation']} |",
        f"| Credit officer | {decision['officer']} ({decision['action']}) |",
    ]
    if decision.get("reason"):
        lines.append(f"| Override reason | {decision['reason']} |")

    # Incomplete applications: explain why there's no analysis
    if completeness.get("missing_sections"):
        lines += [
            "",
            "## Application status",
            "",
            f"Application incomplete. Missing sections: **{', '.join(completeness['missing_sections'])}**. "
            "The application was routed directly to the credit officer without AI assessment.",
        ]

    if terms:
        lines += ["", "## Extracted loan terms", "", "| Term | Value |", "|---|---|"]
        for key, label in TERM_LABELS.items():
            lines.append(f"| {label} | {format_value(key, terms.get(key))} |")

    if compliance:
        lines += ["", "## Policy compliance", "",
                  "| Rule | Requirement | Severity | Result | Actual |",
                  "|---|---|---|---|---|"]
        for r in compliance:
            lines.append(f"| {r['rule_id']} | {r['description']} | {r['severity']} | "
                         f"{STATUS_ICONS[r['status']]} | {r['actual_value']} |")

    if risk:
        lines += ["", "## AI risk assessment", "",
                  f"**Risk rating:** {risk['risk_rating']}  ",
                  f"**Recommendation:** {risk['recommendation']}",
                  "", "### Key risks"]
        lines += [f"- {item}" for item in risk["key_risks"]] or ["- None identified"]
        lines += ["", "### Mitigants"]
        lines += [f"- {item}" for item in risk["mitigants"]] or ["- None identified"]
        lines += ["", "### Summary", "", risk["summary"]]

    lines += ["", "## Audit trail", "", "| Time | Agent | Action |", "|---|---|---|"]
    for entry in state["audit_log"]:
        lines.append(f"| {entry['time']} | {entry['agent']} | {entry['message']} |")

    lines += ["", "---",
              "*Generated by the multi-agent deal review pipeline. "
              "AI outputs are recommendations only; the final decision rests with the credit officer.*"]
    return "\n".join(lines)


def save_report(state: dict, source_file: str) -> tuple[Path, Path]:
    OUTPUT_DIR.mkdir(exist_ok=True)
    stem = Path(source_file).stem   # e.g. "deal_a_clean"

    md_path = OUTPUT_DIR / f"{stem}_review.md"
    md_path.write_text(build_markdown(state, source_file), encoding="utf-8")

    # Machine-readable record: everything except the raw document and policy
    record = {key: value for key, value in state.items() if key not in ("document", "policy")}
    json_path = OUTPUT_DIR / f"{stem}_decision.json"
    json_path.write_text(json.dumps(record, indent=2), encoding="utf-8")

    return md_path, json_path